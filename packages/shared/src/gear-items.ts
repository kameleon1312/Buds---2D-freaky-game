/** Coin shop price: rarer and later items cost more. */
export function priceOf(rarity: Rarity, minLevel: number): number {
  const base: Record<Rarity, [number, number]> = {
    common: [100, 20],
    uncommon: [300, 60],
    rare: [800, 120],
    epic: [2000, 200],
    legendary: [4000, 400],
    mythic: [8000, 800],
  };
  const [flat, perLevel] = base[rarity];
  return flat + perLevel * minLevel;
}

const SOLD_IN_SHOP: readonly Rarity[] = ['common', 'uncommon', 'rare'];

export const GEAR_ITEMS: CatalogItem[] = BY_SLOT.flatMap(([slot, rows]) =>
  rows.map(([id, name, rarity, minLevel, bonus, description, weapon]): CatalogItem => ({
    id,
    kind: weapon ? 'weapon' : 'gear',
    name,
    rarity,
    price: { currency: 'coins', amount: priceOf(rarity, minLevel) },
    premium: false,
    available: true,
    slot,
    bonus,
    shop: SOLD_IN_SHOP.includes(rarity),
    loot: true,
    minLevel,
    weapon,
    description,
  })),
);
