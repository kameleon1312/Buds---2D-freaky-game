// Writes every district map and every interior to apps/unity/Assets/Buds/Resources/Maps/<id>.txt and checks
// them (spawn, exits and doors reachable, signs reachable, every prop known, every door leads to a room whose
// way out leads back to that district).
//
// Usage (from apps/api): pnpm exec tsx ../../tools/world/export-maps.ts [--preview dir]
import { mkdirSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import type { MapCanvas } from './maps/lib';
import { dworCarski } from './maps/dwor-carski';
import { dzikaPuszcza } from './maps/dzika-puszcza';
import { interiors } from './maps/interiors';
import { lasPalmas } from './maps/las-palmas';
import { losKarkos } from './maps/los-karkos';
import { miastoZiomkow } from './maps/miasto-ziomkow';
import { routes } from './maps/routes';
import { wyspaStartowa } from './maps/wyspa-startowa';

const districts = [miastoZiomkow, dzikaPuszcza, lasPalmas, dworCarski, losKarkos].map((build) =>
  build(),
);
const rooms = interiors();

const problems: string[] = [];
for (const d of districts)
  for (const door of d.doors) {
    const room = rooms.find((r) => r.id === door.target);
    if (!room) problems.push(`${d.id}: door to unknown room ${door.target}`);
    else if (room.outside !== d.id)
      problems.push(`${room.id}: leads out to ${room.outside}, not ${d.id}`);
  }
for (const r of rooms)
  if (!districts.some((d) => d.doors.some((door) => door.target === r.id)))
    problems.push(`${r.id}: no door leads into it`);
if (problems.length) throw new Error(`Maps have problems:\n  - ${problems.join('\n  - ')}`);

const dir = fileURLToPath(new URL('../../apps/unity/Assets/Buds/Resources/Maps/', import.meta.url));
mkdirSync(dir, { recursive: true });
// the tutorial island: its pier leads to Miasto Ziomków, one way
const island = wyspaStartowa();

// the wastelands between the cities (travel.ts ROUTES): every city's road out leads onto one
const wastelands = routes();
for (const w of wastelands)
  for (const end of [w.exits[0]!, w.exits[1]!]) {
    const city = districts.find((d) => d.id === end.district);
    if (!city?.exits.some((e) => e.district === w.id))
      throw new Error(`${w.id}: ${end.district} has no road out onto it`);
  }

for (const map of [...districts, island, ...wastelands, ...rooms] as MapCanvas[]) {
  const { reachable, walkable } = map.validate();
  writeFileSync(`${dir}${map.id}.txt`, map.toText());
  console.info(`${map.id}: ${map.w}×${map.h}, ${reachable}/${walkable} walkable cells reachable`);
}

// ---------- walk grids: which cells a bud can stand on, for the live server's movement checks ----------
// packages/shared/src/walk-grids.ts: one bit per cell (1 = walkable), row by row from the north edge, base64.
const grids: string[] = [];
for (const map of [...districts, island, ...wastelands, ...rooms] as MapCanvas[]) {
  const bytes = new Uint8Array(Math.ceil((map.w * map.h) / 8));
  for (let y = 0; y < map.h; y++)
    for (let x = 0; x < map.w; x++) {
      const i = y * map.w + x;
      if (map.walkable(x, y)) bytes[i >> 3]! |= 1 << (i & 7);
    }
  grids.push(
    `  '${map.id}': { w: ${map.w}, h: ${map.h}, bits: '${Buffer.from(bytes).toString('base64')}' },`,
  );
}
const gridFile = fileURLToPath(new URL('../../packages/shared/src/walk-grids.ts', import.meta.url));
writeFileSync(
  gridFile,
  `// Generated by tools/world/export-maps.ts from the map files: do not edit by hand.
// One bit per cell (1 = a bud can stand there), row by row from the north edge, base64. The live server checks
// every position against these (live.ts), so nobody is seen walking through walls.

export const WALK_GRIDS: Readonly<Record<string, { w: number; h: number; bits: string }>> = {
${grids.join('\n')}
};
`,
);
console.info(`${grids.length} walk grids → ${gridFile}`);

// ---------- rewiry (turfs): every zone of every district, for the server's rivalry rules ----------
// packages/shared/src/turfs.ts is generated here so the server, the content and the maps always agree.
const PREFIX: Record<string, string> = {
  'miasto-ziomkow': 'mz',
  'dzika-puszcza': 'dp',
  'las-palmas': 'lp',
  'dwor-carski': 'dc',
  'los-karkos': 'lk',
};
const ascii = (s: string) =>
  s
    .toLowerCase()
    .replace(/ą/g, 'a')
    .replace(/ć/g, 'c')
    .replace(/ę/g, 'e')
    .replace(/ł/g, 'l')
    .replace(/ń/g, 'n')
    .replace(/ó/g, 'o')
    .replace(/ś/g, 's')
    .replace(/[źż]/g, 'z')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '');
const turfs: string[] = [];
const roomDoors: string[] = [];
for (const d of districts) {
  const prefix = PREFIX[d.id];
  if (!prefix) throw new Error(`no turf prefix for ${d.id}`);
  const seen = new Set<string>();
  for (const z of d.zones) {
    const id = `${prefix}-${ascii(z.name)}`.slice(0, 40);
    if (seen.has(id)) throw new Error(`${d.id}: two zones make turf ${id}`);
    seen.add(id);
    const [x0, y0, x1, y1] = z.r;
    turfs.push(
      `  { id: '${id}', district: '${d.id}', name: '${z.name.replace(/'/g, "\\'")}', x0: ${x0}, y0: ${y0}, x1: ${x1}, y1: ${y1} },`,
    );
  }
  for (const door of d.doors)
    roomDoors.push(`  '${door.target}': ['${d.id}', ${door.x}, ${door.y}],`);
}
const turfFile = fileURLToPath(new URL('../../packages/shared/src/turfs.ts', import.meta.url));
writeFileSync(
  turfFile,
  `// Generated by tools/world/export-maps.ts from the district maps: do not edit by hand.
import type { Turf } from './rivalry';

/** Rewiry: every named zone of every district (map coordinates, inclusive). */
export const TURFS: readonly Turf[] = [
${turfs.join('\n')}
];

/** Rooms (interiors) by id: the district and the cell of their door, so things inside count for that turf. */
export const ROOM_DOORS: Readonly<Record<string, readonly [district: string, x: number, y: number]>> = {
${roomDoors.join('\n')}
};
`,
);
console.info(`${turfs.length} turfs → ${turfFile}`);
