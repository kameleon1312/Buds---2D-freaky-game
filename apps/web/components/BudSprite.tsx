import {
  VIEW_H,
  VIEW_W,
  budFrameMarkup,
  type BudLook,
  type Facing,
  type WalkFrame,
} from '@buds/shared';

type Props = {
  look: BudLook;
  /** rendered height in px; width follows the 2:3 frame */
  height?: number;
  facing?: Facing;
  frame?: WalkFrame;
  /** side views face left; flip to face right */
  flip?: boolean;
  className?: string;
  label?: string;
  /** show only the head (faces in picker thumbnails) */
  crop?: 'head';
};

// head + tallest hair (afro, bun) fits in this square
const HEAD_BOX = { x: 16, y: -6, w: 128, h: 132 };

export function BudSprite({
  look,
  height = 96,
  facing = 'down',
  frame = 0,
  flip = false,
  className,
  label,
  crop,
}: Props) {
  const box = crop === 'head' ? HEAD_BOX : { x: 0, y: 0, w: VIEW_W, h: VIEW_H };
  const markup = budFrameMarkup(look, facing, frame);
  return (
    <svg
      viewBox={`${box.x} ${box.y} ${box.w} ${box.h}`}
      width={Math.round((height * box.w) / box.h)}
      height={height}
      role="img"
      aria-label={label ?? 'Bud'}
      className={['bud-sprite', className].filter(Boolean).join(' ')}
    >
      <g
        transform={flip ? `translate(${VIEW_W} 0) scale(-1 1)` : undefined}
        // markup is generated by our own code from a validated look — no user strings inside
        dangerouslySetInnerHTML={{ __html: markup }}
      />
    </svg>
  );
}
