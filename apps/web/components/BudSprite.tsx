import { useId } from 'react';
import {
  VIEW_H,
  VIEW_W,
  budFrameMarkup,
  type BudLook,
  type Facing,
  type WalkFrame,
} from '@buds/shared';

type Props = {
  look: BudLook;
  /** rendered height in px; width follows the 2:3 frame */
  height?: number;
  facing?: Facing;
  frame?: WalkFrame;
  /** side views face left; flip to face right */
  flip?: boolean;
  className?: string;
  label?: string;
  /** show only a part (picker thumbnails) */
  crop?: BudCrop;
};

export type BudCrop = 'head' | 'hair' | 'face' | 'torso' | 'legs' | 'feet';

// what each crop shows, in the frame's units; head + tallest hair (afro, bun) fits in the first
const CROPS: Record<BudCrop, { x: number; y: number; w: number; h: number }> = {
  head: { x: 16, y: -6, w: 128, h: 132 },
  hair: { x: 24, y: 10, w: 112, h: 100 },
  face: { x: 38, y: 50, w: 84, h: 72 },
  torso: { x: 18, y: 120, w: 124, h: 82 },
  legs: { x: 30, y: 166, w: 100, h: 66 },
  feet: { x: 30, y: 192, w: 100, h: 40 },
};

export function BudSprite({
  look,
  height = 96,
  facing = 'down',
  frame = 0,
  flip = false,
  className,
  label,
  crop,
}: Props) {
  const box = crop ? CROPS[crop] : { x: 0, y: 0, w: VIEW_W, h: VIEW_H };
  // clip ids are the drawing's own, so the same bud twice on a page would share them; a clip inside a hidden copy
  // then does nothing and the colours run out of the outline. Every sprite gets ids of its own.
  const own = useId().replace(/[^a-zA-Z0-9]/g, '');
  const markup = budFrameMarkup(look, facing, frame)
    .replace(/<clipPath id="/g, `<clipPath id="${own}-`)
    .replace(/url\(#/g, `url(#${own}-`);
  return (
    <svg
      viewBox={`${box.x} ${box.y} ${box.w} ${box.h}`}
      width={Math.round((height * box.w) / box.h)}
      height={height}
      preserveAspectRatio="xMidYMid meet"
      role="img"
      aria-label={label ?? 'Bud'}
      className={['bud-sprite', className].filter(Boolean).join(' ')}
    >
      <g
        transform={flip ? `translate(${VIEW_W} 0) scale(-1 1)` : undefined}
        // markup is generated by our own code from a validated look — no user strings inside
        dangerouslySetInnerHTML={{ __html: markup }}
      />
    </svg>
  );
}
